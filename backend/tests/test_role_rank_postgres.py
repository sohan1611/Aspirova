def insert_fixtures(connection):
    return connection.execute(
        insert(OPPORTUNITIES)
        .values(
            [
                {
                    "slug": str(index),
                    "title": row["title"],
                    "category": row.get("category", "job"),
                    "meta": row.get("meta"),
                }
                for index, row in enumerate(FIXTURES)
            ]
        )
        .returning(OPPORTUNITIES.c.id, OPPORTUNITIES.c.slug, OPPORTUNITIES.c.role_rank)
    ).all()


def expected_rank(row):
    level = classify_role_level(
        row["title"], row.get("category", "job"), row.get("meta"), overrides={}
    )["level"]
    return {"internship": 0, "apprenticeship": 0, "experienced": 2}.get(level, 1)


def test_migration_no_rewrite_or_backfill_and_downgrade(rank_schema, migration):
    connection = rank_schema
    schema = connection.scalar(text("SELECT current_schema()"))
    connection.exec_driver_sql(
        "INSERT INTO opportunities(slug, title, category) VALUES ('legacy', 'Senior Engineer', 'job')"
    )
    heap = connection.scalar(text("SELECT pg_relation_filenode('opportunities'::regclass)"))
    migration.upgrade()
    assert connection.scalar(text("SELECT role_rank FROM opportunities")) is None
    assert connection.scalar(text("SELECT pg_relation_filenode('opportunities'::regclass)")) == heap
    assert tuple(
        connection.execute(
            text(
                "SELECT provolatile, proparallel, prorettype::regtype::text FROM pg_proc "
                "WHERE oid='opportunity_role_rank(text,text,jsonb)'::regprocedure"
            )
        ).one()
    ) == ("i", "s", "smallint")
    migration.downgrade()
    assert connection.scalar(text("SELECT count(*) FROM opportunities")) == 1
    for signature in ("opportunity_role_rank(text,text,jsonb)", "set_opportunity_role_rank()"):
        assert (
            connection.scalar(
                text("SELECT to_regprocedure(:signature)"), {"signature": f'"{schema}".{signature}'}
            )
            is None
        )
    assert (
        connection.scalar(
            text(
                "SELECT count(*) FROM pg_attribute WHERE attrelid='opportunities'::regclass "
                "AND attname='role_rank' AND NOT attisdropped"
            )
        )
        == 0
    )


def test_trigger_stored_function_and_fallback_parity(rank_db):
    inserted = insert_fixtures(rank_db)
    assert len(inserted) == 96
    for _, slug, rank in inserted:
        assert rank == expected_rank(FIXTURES[int(slug)]), FIXTURES[int(slug)]["title"]
    opportunity = OPPORTUNITIES.c
    results = rank_db.execute(
        select(
            opportunity.slug,
            opportunity.role_rank,
            func.opportunity_role_rank(opportunity.title, opportunity.category, opportunity.meta),
            role_rank_fallback_expression(opportunity),
            student_rank_expression(opportunity, overrides={}),
        )
    ).all()
    for slug, stored, sql_function, fallback, read_rank in results:
        assert stored == sql_function == fallback == read_rank == expected_rank(FIXTURES[int(slug)])


def test_trigger_recomputes_only_for_title_category_meta(rank_db):
    rank_db.exec_driver_sql(
        "INSERT INTO opportunities(slug,title,category) VALUES ('trigger', 'Senior Engineer', 'job')"
    )

    def rank():
        return rank_db.scalar(text("SELECT role_rank FROM opportunities WHERE slug='trigger'"))

    assert rank() == 2
    rank_db.exec_driver_sql("UPDATE opportunities SET title='Software Engineer'")
    assert rank() == 1
    rank_db.exec_driver_sql("UPDATE opportunities SET category='internship'")
    assert rank() == 0
    rank_db.exec_driver_sql("UPDATE opportunities SET category='job'")
    assert rank() == 1
    rank_db.exec_driver_sql(
        """UPDATE opportunities SET meta='{"eligible_experienced_only":true}'::jsonb"""
    )
    assert rank() == 2
    rank_db.exec_driver_sql("UPDATE opportunities SET title='Senior Intern'")
    assert rank() == 0
    # A sentinel proves last_seen_at does not merely recompute the same value.
    rank_db.exec_driver_sql("UPDATE opportunities SET role_rank=7")
    rank_db.exec_driver_sql("UPDATE opportunities SET last_seen_at=now() + interval '1 day'")
    assert rank() == 7
    rank_db.exec_driver_sql("UPDATE opportunities SET title=title")
    assert rank() == 0


@pytest.mark.parametrize("stored", [True, False])
def test_null_fallback_and_query_overrides(rank_db, stored):
    insert_fixtures(rank_db)
    if not stored:
        rank_db.exec_driver_sql("UPDATE opportunities SET role_rank=NULL")
    opportunity = OPPORTUNITIES.c
    normal = rank_db.execute(
        select(opportunity.slug, student_rank_expression(opportunity, overrides={}))
    ).all()
    for slug, rank in normal:
        assert rank == expected_rank(FIXTURES[int(slug)])
    for level in ROLE_LEVELS:
        overrides = {
            str(index): {"slug": str(index), "level": level, "reason": "Reviewed fixture"}
            for index in range(len(FIXTURES))
        }
        ranks = rank_db.scalars(
            select(student_rank_expression(opportunity, overrides=overrides))
        ).all()
        assert set(ranks) == {
            {"internship": 0, "apprenticeship": 0, "experienced": 2}.get(level, 1)
        }


@pytest.mark.parametrize("batch", [1, 31, 2000])
def test_backfill_batches_dry_run_and_idempotence(rank_db, batch, capsys):
    inserted = insert_fixtures(rank_db)
    rank_db.exec_driver_sql("UPDATE opportunities SET role_rank=NULL WHERE slug <> '0'")
    statements = []

    def capture(conn, cursor, statement, parameters, context, executemany):
        statements.append(statement)

    event.listen(rank_db, "before_cursor_execute", capture)
    try:
        assert backfill_role_rank(rank_db, batch=batch, dry_run=True) == {
            "updated": 0,
            "remaining_null": len(inserted) - 1,
        }
        assert not any(statement.startswith("UPDATE ") for statement in statements)
        assert backfill_role_rank(rank_db, batch=batch) == {
            "updated": len(inserted) - 1,
            "remaining_null": 0,
        }
        assert sum(statement.startswith("UPDATE ") for statement in statements) == math.ceil(
            95 / batch
        )
        assert any(statement == "SET LOCAL lock_timeout = '3s'" for statement in statements)
        assert any(statement == "SET LOCAL statement_timeout = '30s'" for statement in statements)
        assert backfill_role_rank(rank_db, batch=batch) == {"updated": 0, "remaining_null": 0}
    finally:
        event.remove(rank_db, "before_cursor_execute", capture)
    assert re.fullmatch(r"(?:rows_updated=\d+ remaining_null=\d+\n){3}", capsys.readouterr().out)
    for slug, rank in rank_db.execute(select(OPPORTUNITIES.c.slug, OPPORTUNITIES.c.role_rank)):
        assert rank == expected_rank(FIXTURES[int(slug)])


def test_backfill_fills_live_rows_by_default_and_closed_rows_only_with_all(rank_db):
    insert_fixtures(rank_db)
    rank_db.exec_driver_sql("UPDATE opportunities SET role_rank=NULL")
    rank_db.exec_driver_sql("UPDATE opportunities SET status='expired' WHERE slug IN ('1', '2')")
    assert backfill_role_rank(rank_db, batch=50) == {
        "updated": len(FIXTURES) - 2,
        "remaining_null": 0,
    }
    still_null = rank_db.scalars(
        select(OPPORTUNITIES.c.slug).where(OPPORTUNITIES.c.role_rank.is_(None))
    ).all()
    assert sorted(still_null) == ["1", "2"]
    assert backfill_role_rank(rank_db, batch=50, include_inactive=True) == {
        "updated": 2,
        "remaining_null": 0,
    }
