const FALLBACK_COUNTRY_NAMES: Record<string, string> = {
  XK: "Kosovo",
};

const regionNames = new Intl.DisplayNames(["en"], { type: "region" });

export function countryFlag(code: string): string {
  const normalizedCode = code.trim().toUpperCase();

  if (!/^[A-Z]{2}$/.test(normalizedCode)) return "🌍";

  return String.fromCodePoint(
    ...Array.from(normalizedCode, (character) =>
      0x1f1e6 + character.charCodeAt(0) - "A".charCodeAt(0),
    ),
  );
}

export const COUNTRIES: Country[] = ISO_3166_1_ALPHA_2.map((code) => ({
  code,
  name: FALLBACK_COUNTRY_NAMES[code] ?? regionNames.of(code) ?? code,
  flag: countryFlag(code),
})).sort((first, second) => first.name.localeCompare(second.name, "en"));

export function getCountry(code: string | null | undefined): Country | undefined {
  const normalizedCode = code?.trim().toUpperCase();
  return COUNTRIES.find((country) => country.code === normalizedCode);
}
